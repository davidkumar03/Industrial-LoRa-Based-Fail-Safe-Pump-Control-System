				  // Maps 0-100 to your Timer Period (41999)

				  uint32_t pulse = (uint32_t)((duty_val * 41999) / 100);
				  __HAL_TIM_SET_COMPARE(&htim1, TIM_CHANNEL_1, pulse);

					//  Telemetry Logging
				  int rssi = LoRa_getRSSI(&myLoRa);
				  if(!uart_busy)
				  {
					  char msg[50];
					  sprintf(msg, "[SLAVE] Valid Command: RSSI: %d dBm\r\n", rssi);
					  HAL_UART_Transmit(&huart2, (uint8_t*)msg, strlen(msg), 100);
				  }
				  // --- 2. UART DISPLAY ---
